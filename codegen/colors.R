# Color palette codegen: writes R/zz-gen-colors.R (plotly_colors) from
# codegen/resources/plotly-colors.json, which codegen/resources/plotly_colors.py dumps
# from plotly.py's plotly.colors modules.

write_colors <- function(outdir = ".") {
  cols <- jsonlite::read_json(file.path(
    outdir,
    "codegen",
    "resources",
    "plotly-colors.json"
  ))
  fmt_group <- function(group) {
    entries <- vapply(
      names(group),
      function(n) {
        vals <- paste0('"', unlist(group[[n]]), '"', collapse = ", ")
        paste0("    ", n, " = c(", vals, ")")
      },
      ""
    )
    paste0("list(\n", paste(entries, collapse = ",\n"), "\n  )")
  }
  types <- c("qualitative", "sequential", "diverging", "cyclical")
  src <- c(
    sprintf(
      "# Generated by codegen/colors.R from plotly.py %s (plotly.colors). Do not edit by hand.",
      cols$plotly_version
    ),
    "",
    "#' Color sequences and scales",
    "#'",
    "#' The named color sequences and scales of plotly.py's \\code{plotly.colors} module:",
    "#' \\code{plotly_colors$qualitative} (discrete color sequences, e.g. \\code{Plotly},",
    "#' \\code{D3}, \\code{Set1}), \\code{plotly_colors$sequential} (e.g. \\code{Viridis},",
    "#' \\code{Plasma}, \\code{Blues}), \\code{plotly_colors$diverging} (e.g. \\code{RdBu}) and",
    "#' \\code{plotly_colors$cyclical} (e.g. \\code{Twilight}). Each is a character vector",
    "#' of colors; use \\code{rev()} to reverse one.",
    "#'",
    "#' Sequential, diverging and cyclical scales can also be given by name",
    "#' (case-insensitive, with \\code{\"_r\"} appended to reverse) to any colorscale",
    "#' property, e.g. \\code{marker = list(colorscale = \"viridis_r\")}.",
    "#'",
    "#' @format A list of four named lists of character vectors.",
    "#' @noMd",
    "#' @export",
    "#' @examples",
    "#' names(plotly_colors$qualitative)",
    "#' plotly_colors$qualitative$Plotly",
    "#' rev(plotly_colors$sequential$Viridis)",
    "plotly_colors <- list(",
    paste0(
      "  ",
      types,
      " = ",
      vapply(types, function(t) fmt_group(cols[[t]]), ""),
      collapse = ",\n"
    ),
    ")",
    ""
  )
  writeLines(src, file.path(outdir, "R", "zz-gen-colors.R"))
  message(sprintf(
    "Wrote plotly_colors: %s",
    paste(sprintf("%d %s", lengths(cols[types]), types), collapse = ", ")
  ))
}

# plotly.js's built-in named colorscales (Blues, Reds, Viridis, ...), read
# from the bundled plotly.js: a named colorscale plotly.js knows expands to
# plotly.js's definition, so it looks as it does in plotly.js and the
# plotly package.
PLOTLYJS_COLORSCALES <- c(
  "Greys",
  "YlGnBu",
  "Greens",
  "YlOrRd",
  "Bluered",
  "RdBu",
  "Reds",
  "Blues",
  "Picnic",
  "Rainbow",
  "Portland",
  "Jet",
  "Hot",
  "Blackbody",
  "Earth",
  "Electric",
  "Viridis",
  "Cividis"
)

read_plotlyjs_colorscales <- function(path) {
  js <- paste(readLines(path, warn = FALSE), collapse = "\n")
  out <- lapply(PLOTLYJS_COLORSCALES, function(name) {
    m <- regmatches(
      js,
      regexpr(
        paste0("\\b", name, ":\\[\\[[^;]*?\\]\\](?=[,}])"),
        js,
        perl = TRUE
      )
    )
    if (!length(m)) {
      stop("plotly.js colorscale not found: ", name)
    }
    json <- sub(paste0("^", name, ":"), "", m)
    json <- gsub("([\\[,])\\.", "\\10.", json) # .2 -> 0.2
    stops <- jsonlite::fromJSON(json, simplifyVector = FALSE)
    stats::setNames(
      vapply(stops, function(s) as.character(s[[2L]]), ""),
      vapply(stops, function(s) as.numeric(s[[1L]]), 0)
    )
  })
  stats::setNames(out, PLOTLYJS_COLORSCALES)
}
