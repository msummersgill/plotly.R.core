# Development commands for plotly.core (the R counterpart of plotly.py/commands.py).
# Not part of the built package. Run from the package root, e.g.
#
#   Rscript commands.R updateplotlyjs              # latest plotly.js from npm
#   Rscript commands.R updateplotlyjs 4.2.0        # specific version from npm
#   Rscript commands.R updateplotlyjsdev ~/Documents/plotly.js  # local clone
#   Rscript commands.R codegen                     # regenerate from the schema
#
# Updating plotly.js copies the bundle, locales and licence into
# inst/htmlwidgets/lib/plotlyjs, the schema into codegen/resources, and
# rewrites the version in the widget yaml and R/zz-gen-version.R.

PROJECT_ROOT <- normalizePath(".")
PLOTLYJS_DIR <- file.path(PROJECT_ROOT, "inst", "htmlwidgets", "lib", "plotlyjs")
SCHEMA_PATH <- file.path(PROJECT_ROOT, "codegen", "resources", "plot-schema.json")
VERSION_FILE <- file.path(PROJECT_ROOT, "R", "zz-gen-version.R")

# Partial bundles shipped alongside the full one (plotly.js's "strict"
# bundle is left out: it is nearly as large as the full one).
PARTIAL_BUNDLES <- c("basic", "cartesian", "finance", "geo", "gl2d", "gl3d", "map")

# Trace types in a partial bundle, from plotly.js's lib/index-<bundle>.js
# (scatter is part of every bundle's core).
bundle_traces <- function(root, bundle) {
  index <- readLines(file.path(root, "lib", paste0("index-", bundle, ".js")))
  traces <- sub(".*require\\('\\./([a-z0-9]+)'\\).*", "\\1", grep("require\\('\\./[a-z0-9]+'\\)", index, value = TRUE))
  sort(unique(c("scatter", setdiff(traces, c("core", "calendars")))))
}

# Copy plotly.js assets from a plotly.js package root (a git clone, or an
# unpacked npm tarball) into the package.
install_plotlyjs_from <- function(root) {
  dist <- file.path(root, "dist")
  version <- jsonlite::read_json(file.path(root, "package.json"))$version
  sources <- c(
    bundle = file.path(dist, "plotly.min.js"),
    schema = file.path(dist, "plot-schema.json"),
    license = file.path(root, "LICENSE"),
    stats::setNames(file.path(dist, paste0("plotly-", PARTIAL_BUNDLES, ".min.js")), PARTIAL_BUNDLES)
  )
  locales <- list.files(dist, "^plotly-locale-.*\\.js$", full.names = TRUE)
  missing <- sources[!file.exists(sources)]
  if (length(missing)) stop("Missing plotly.js files: ", paste(missing, collapse = ", "))
  if (!length(locales)) stop("No locale files found in ", dist)

  # Check everything exists before writing, so a failure leaves no partial update.
  locale_dir <- file.path(PLOTLYJS_DIR, "locales")
  dir.create(locale_dir, recursive = TRUE, showWarnings = FALSE)
  dir.create(dirname(SCHEMA_PATH), recursive = TRUE, showWarnings = FALSE)
  unlink(list.files(locale_dir, full.names = TRUE))

  ok <- c(
    file.copy(sources[["bundle"]], file.path(PLOTLYJS_DIR, "plotly.min.js"), overwrite = TRUE),
    file.copy(sources[PARTIAL_BUNDLES], file.path(PLOTLYJS_DIR, basename(sources[PARTIAL_BUNDLES])), overwrite = TRUE),
    file.copy(sources[["license"]], file.path(PLOTLYJS_DIR, "LICENSE"), overwrite = TRUE),
    file.copy(sources[["schema"]], SCHEMA_PATH, overwrite = TRUE),
    file.copy(locales, file.path(locale_dir, sub("^plotly-locale-", "", basename(locales))))
  )
  if (!all(ok)) stop("Failed to copy some plotly.js files")
  # the schema shipped with the package, for schema()
  gz <- gzfile(file.path(PROJECT_ROOT, "inst", "schema", "plot-schema.json.gz"), "w", compression = 9)
  writeLines(readLines(SCHEMA_PATH, warn = FALSE), gz)
  close(gz)

  writeLines(c(
    "# This file is generated by the updateplotlyjs and updateplotlyjsdev commands in commands.R",
    "# Do not edit by hand.",
    "",
    "#' Version of the bundled plotly.js library",
    "#' @return A character string.",
    "#' @export",
    "#' @examples",
    "#' plotlyjs_version()",
    sprintf('plotlyjs_version <- function() "%s"', version),
    "",
    "# Trace types in each partial bundle shipped in inst/htmlwidgets/lib/plotlyjs",
    "PLOTLYJS_BUNDLE_TRACES <- list(",
    paste0("  ", PARTIAL_BUNDLES, " = c(", vapply(PARTIAL_BUNDLES, function(b) paste0('"', bundle_traces(root, b), '"', collapse = ", "), ""), ")",
           c(rep(",", length(PARTIAL_BUNDLES) - 1L), "")),
    ")"
  ), VERSION_FILE)

  message("Updated plotly.js to ", version, " (", length(locales), " locales)")
  invisible(version)
}

# Download a released plotly.js from the npm registry.
update_plotlyjs <- function(version = "latest") {
  if (identical(version, "latest")) {
    meta <- curl::curl_fetch_memory("https://registry.npmjs.org/plotly.js/latest")
    version <- jsonlite::fromJSON(rawToChar(meta$content))$version
  }
  url <- sprintf("https://registry.npmjs.org/plotly.js/-/plotly.js-%s.tgz", version)
  tmp <- tempfile("plotlyjs-")
  dir.create(tmp)
  on.exit(unlink(tmp, recursive = TRUE), add = TRUE)
  tarball <- file.path(tmp, "plotly.js.tgz")
  message("Downloading ", url)
  curl::curl_download(url, tarball)
  utils::untar(tarball, exdir = tmp)
  install_plotlyjs_from(file.path(tmp, "package"))
}

# Use a local plotly.js clone (must have been built so dist/ is current).
update_plotlyjs_dev <- function(path = "~/Documents/plotly.js") {
  install_plotlyjs_from(normalizePath(path, mustWork = TRUE))
}

# Generate validators (and, later, graph objects) from the plotly.js schema.
codegen <- function() {
  for (f in c("utils.R", "validators.R", "datatypes.R", "figure.R", "colors.R", "generate.R")) source(file.path(PROJECT_ROOT, "codegen", f))
  perform_codegen(PROJECT_ROOT)
}

if (sys.nframe() == 0L) {
  args <- commandArgs(trailingOnly = TRUE)
  cmd <- if (length(args)) args[[1]] else ""
  switch(cmd,
    updateplotlyjs = update_plotlyjs(if (length(args) > 1) args[[2]] else "latest"),
    updateplotlyjsdev = update_plotlyjs_dev(if (length(args) > 1) args[[2]] else "~/Documents/plotly.js"),
    codegen = codegen(),
    stop("Usage: Rscript commands.R <codegen | updateplotlyjs [version] | updateplotlyjsdev [path]>")
  )
}
